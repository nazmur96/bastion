import { createHash } from 'node:crypto'
import { chmodSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { runProcess } from '@orca/process-host'
import type { RecipeFile } from '../../../shared/fork-recipes/object-storage-recipe'
import type { RecipeStep } from '../../../shared/fork-recipes/recipe-contract'
import { recipeFingerprint } from './recipe-fingerprint'
import type { TerraformTool } from './terraform-tool'

export type RunTerraform = typeof runProcess
/** Provider settings only a local Floci run needs; never written into the project. */
export const FLOCI_OVERRIDE = `# Generated by Bastion for a local Floci run only; never written into the project.
provider "aws" {
  skip_credentials_validation = true
  skip_metadata_api_check     = true
  skip_requesting_account_id  = true
  s3_use_path_style           = true
}
`
export const OVERRIDE_NAME = 'zz_bastion_floci_override.tf'

/**
 * Resource types Floci serves through real Docker backends, which Bastion's restricted emulator
 * forbids. Floci may accept their creation but cannot delete them (for example ECR's backing
 * registry), so delivering them to Floci would leave stuck resources. Validate only; apply on a
 * real target.
 */
const FLOCI_DOCKER_BACKED =
  /resource\s+"(aws_db_instance|aws_rds_cluster|aws_ecr_repository|aws_instance|aws_launch_template|aws_ecs_[a-z_]+|aws_eks_[a-z_]+|aws_lambda_function|aws_elasticache_[a-z_]+|aws_msk_[a-z_]+|aws_memorydb_[a-z_]+|aws_neptune_[a-z_]+|aws_docdb_[a-z_]+)"/

export function flociUnsupportedResource(files: RecipeFile[]): string | null {
  for (const file of files) {
    const match = file.content.match(FLOCI_DOCKER_BACKED)
    if (match) {
      return match[1]
    }
  }
  return null
}

export class RecipeRunError extends Error {
  constructor(readonly code: 'changed' | 'failed' | 'emulator-unsupported') {
    super(code)
  }
}

function privateDirectory(path: string): string {
  mkdirSync(path, { recursive: true, mode: 0o700 })
  if (process.platform !== 'win32') {
    chmodSync(path, 0o700)
  }
  return path
}
/** Replaces the source files in a run directory, keeping its .terraform and state. */
function syncFiles(directory: string, files: RecipeFile[], override: boolean): void {
  for (const name of readdirSync(directory)) {
    if (name !== '.terraform' && !name.includes('.tfstate') && name !== '.terraform.lock.hcl') {
      rmSync(join(directory, name), { recursive: true, force: true })
    }
  }
  for (const file of files) {
    writeFileSync(join(directory, file.path.split('/').at(-1) ?? ''), file.content, { mode: 0o600 })
  }
  if (override) {
    writeFileSync(join(directory, OVERRIDE_NAME), FLOCI_OVERRIDE, { mode: 0o600 })
  }
}
function baseEnv(owner: NodeJS.ProcessEnv, pluginCache: string): Record<string, string> {
  const env: Record<string, string> = {}
  for (const name of [
    'PATH',
    'HOME',
    'USERPROFILE',
    'TMPDIR',
    'TMP',
    'TEMP',
    'SystemRoot',
    'LANG'
  ]) {
    if (owner[name]) {
      env[name] = owner[name]
    }
  }
  return {
    ...env,
    TF_IN_AUTOMATION: '1',
    TF_INPUT: '0',
    CHECKPOINT_DISABLE: '1',
    TF_PLUGIN_CACHE_DIR: pluginCache
  }
}
/** The first meaningful line of Terraform output, without its diagnostic box drawing. */
function firstLine(text: string): string | null {
  const line = text
    .split('\n')
    .map((value) => value.replace(/^[╷│╵]\s*/, '').trim())
    .find(Boolean)
  return line ? line.slice(0, 240) : null
}
async function step(
  run: RunTerraform,
  tool: TerraformTool,
  name: RecipeStep['step'],
  args: string[],
  cwd: string,
  env: Record<string, string>,
  timeoutMs: number
): Promise<RecipeStep & { stdout: string }> {
  const result = await run({
    program: tool.executable,
    args,
    cwd,
    env,
    timeoutMs,
    maxOutputBytes: 1024 * 1024,
    killOnOutputLimit: true
  })
  const ok = result.code === 0 && !result.timedOut && !result.outputTruncated
  const text = `${result.stderr}\n${result.stdout}`
  return {
    step: name,
    ok,
    message: ok
      ? null
      : result.timedOut
        ? 'Timed out.'
        : (text.match(/Error: [^\n]+/)?.[0] ?? firstLine(text) ?? 'Failed.').slice(0, 240),
    stdout: result.stdout
  }
}

export type RecipeRunContext = {
  /** Bastion's private data root for this workspace. */
  dataRoot: string
  owner: NodeJS.ProcessEnv
  tool: TerraformTool
  run?: RunTerraform
}

/** fmt, init (no backend) and validate on a private copy; the project gets no .terraform/. */
export async function validateRecipe(
  context: RecipeRunContext,
  directory: string,
  files: RecipeFile[]
): Promise<RecipeStep[]> {
  const run = context.run ?? runProcess
  const base = join(context.dataRoot, 'bastion-recipes')
  const work = join(
    privateDirectory(join(base, 'validate')),
    createHash('sha256').update(directory).digest('hex').slice(0, 16)
  )
  rmSync(work, { recursive: true, force: true })
  privateDirectory(work)
  syncFiles(work, files, false)
  const env = baseEnv(context.owner, privateDirectory(join(base, 'plugin-cache')))
  const steps: RecipeStep[] = []
  for (const [name, args, timeout] of [
    ['fmt', ['fmt', '-check', '-recursive', '-no-color'], 30000],
    ['init', ['init', '-backend=false', '-input=false', '-no-color'], 180000],
    ['validate', ['validate', '-no-color'], 60000]
  ] as const) {
    const result = await step(run, context.tool, name, [...args], work, env, timeout)
    steps.push({ step: result.step, ok: result.ok, message: result.message })
    if (!result.ok) {
      break
    }
  }
  return steps
}

/**
 * Apply or destroy the reviewed files on a local Floci target. The files are re-read by the
 * caller and must still match the reviewed fingerprint; state stays in Bastion's private run
 * directory for this emulator instance.
 */
export async function deliverRecipeToFloci(
  context: RecipeRunContext,
  request: {
    operation: 'apply' | 'destroy'
    directory: string
    files: RecipeFile[]
    reviewedFingerprint: string
    instanceId: string
    flociEnv: Record<string, string>
  }
): Promise<{ steps: RecipeStep[]; outputs: Record<string, string> }> {
  if (recipeFingerprint(request.files) !== request.reviewedFingerprint) {
    throw new RecipeRunError('changed')
  }
  if (flociUnsupportedResource(request.files)) {
    throw new RecipeRunError('emulator-unsupported')
  }
  const run = context.run ?? runProcess
  const base = join(context.dataRoot, 'bastion-recipes')
  const work = privateDirectory(
    join(
      base,
      'floci',
      request.instanceId,
      createHash('sha256').update(request.directory).digest('hex').slice(0, 16)
    )
  )
  syncFiles(work, request.files, true)
  const env = {
    ...baseEnv(context.owner, privateDirectory(join(base, 'plugin-cache'))),
    ...request.flociEnv
  }
  const steps: RecipeStep[] = []
  const init = await step(
    run,
    context.tool,
    'init',
    ['init', '-input=false', '-no-color'],
    work,
    env,
    180000
  )
  steps.push({ step: init.step, ok: init.ok, message: init.message })
  if (!init.ok) {
    return { steps, outputs: {} }
  }
  const change = await step(
    run,
    context.tool,
    request.operation,
    [request.operation, '-auto-approve', '-input=false', '-no-color'],
    work,
    env,
    300000
  )
  steps.push({ step: change.step, ok: change.ok, message: change.message })
  if (!change.ok || request.operation === 'destroy') {
    return { steps, outputs: {} }
  }
  const output = await step(
    run,
    context.tool,
    'output',
    ['output', '-json', '-no-color'],
    work,
    env,
    30000
  )
  const outputs: Record<string, string> = {}
  try {
    const parsed: unknown = JSON.parse(output.stdout)
    if (parsed && typeof parsed === 'object') {
      for (const [key, value] of Object.entries(parsed).slice(0, 20)) {
        const inner: unknown =
          value && typeof value === 'object' ? Reflect.get(value, 'value') : null
        const sensitive = value && typeof value === 'object' && Reflect.get(value, 'sensitive')
        if (!sensitive && typeof inner === 'string' && /^[\w.:/-]{1,256}$/.test(key + inner)) {
          outputs[key] = inner
        }
      }
    }
  } catch {
    // Outputs are informational; a malformed output list does not undo the apply.
  }
  return { steps, outputs }
}
