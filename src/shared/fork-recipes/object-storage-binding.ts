import { z } from 'zod'
import {
  AWS_PROVIDER_CONSTRAINT,
  bucketNameSchema,
  recipeDirectorySchema,
  recipeTagSchema,
  type RecipeFile
} from './object-storage-recipe'

/**
 * Fork: bind an application to an existing bucket (Step 10.2). Connect before create: the
 * bucket is read as a data source, never created here. Generates a scoped IAM policy (and an
 * optional attachment to an existing role) plus one new application config example file.
 */
export const objectStorageBindingSchema = z
  .object({
    bucket: bucketNameSchema,
    directory: recipeDirectorySchema,
    access: z.enum(['read', 'read-write']),
    roleName: z
      .string()
      .regex(/^[\w+=,.@-]{1,64}$/)
      .nullable(),
    configVariable: z.string().regex(/^[A-Z][A-Z0-9_]{0,63}$/),
    configDirectory: recipeDirectorySchema,
    tags: z.object({ owner: recipeTagSchema, project: recipeTagSchema }).strict()
  })
  .strict()
  .refine((input) => input.configDirectory !== input.directory, {
    message: 'The application config directory must differ from the infra directory.'
  })
export type ObjectStorageBinding = z.infer<typeof objectStorageBindingSchema>

export const BINDING_ACTIONS = {
  read: ['s3:GetObject'],
  'read-write': ['s3:GetObject', 's3:PutObject', 's3:DeleteObject']
} as const

/** `orders-assets` → `ORDERS_ASSETS_BUCKET`, a suggestion the engineer may change. */
export function suggestedConfigVariable(bucket: string): string {
  const base = bucket
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
  const name = /^[A-Z]/.test(base) ? base : `BUCKET_${base}`
  return `${name}_BUCKET`.replace(/_BUCKET_BUCKET$/, '_BUCKET').slice(0, 64)
}

function aligned(entries: [string, string][], indent = ''): string {
  const width = Math.max(...entries.map(([key]) => key.length))
  return entries.map(([key, value]) => `${indent}${key.padEnd(width)} = ${value}`).join('\n')
}

const VERSIONS = `terraform {
  required_version = ">= 1.6"
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "${AWS_PROVIDER_CONSTRAINT}"
    }
  }
}
`
const VARIABLES = `variable "bucket_name" {
  description = "Existing bucket this application uses."
  type        = string
}

variable "access" {
  description = "read or read-write."
  type        = string
  validation {
    condition     = contains(["read", "read-write"], var.access)
    error_message = "access must be read or read-write."
  }
}

variable "role_name" {
  description = "Existing IAM role to attach the policy to, or null."
  type        = string
  default     = null
}

variable "tags" {
  description = "Ownership tags applied to every resource."
  type        = map(string)
  default     = {}
}
`
const MAIN = `locals {
  object_actions = {
    read         = ["s3:GetObject"]
    "read-write" = ["s3:GetObject", "s3:PutObject", "s3:DeleteObject"]
  }
}

# Connect, never create: plan fails if the bucket does not exist.
data "aws_s3_bucket" "this" {
  bucket = var.bucket_name
}

data "aws_iam_policy_document" "access" {
  statement {
    sid       = "ListBucket"
    actions   = ["s3:ListBucket"]
    resources = [data.aws_s3_bucket.this.arn]
  }
  statement {
    sid       = "Objects"
    actions   = local.object_actions[var.access]
    resources = ["\${data.aws_s3_bucket.this.arn}/*"]
  }
}

resource "aws_iam_policy" "access" {
  name        = "\${var.bucket_name}-\${var.access}"
  description = "Application access to \${var.bucket_name}"
  policy      = data.aws_iam_policy_document.access.json
  tags        = var.tags
}

resource "aws_iam_role_policy_attachment" "workload" {
  count      = var.role_name == null ? 0 : 1
  role       = var.role_name
  policy_arn = aws_iam_policy.access.arn
}
`
const OUTPUTS = `output "policy_arn" {
  value = aws_iam_policy.access.arn
}

output "bucket_arn" {
  value = data.aws_s3_bucket.this.arn
}
`
const GITIGNORE = `.terraform/
*.tfstate
*.tfstate.*
crash.log
`

export function renderObjectStorageBinding(input: ObjectStorageBinding): RecipeFile[] {
  const tags = aligned(
    [
      ['"managed-by"', '"bastion-recipe"'],
      ['owner', JSON.stringify(input.tags.owner)],
      ['project', JSON.stringify(input.tags.project)]
    ],
    '  '
  )
  const tfvars = `${aligned([
    ['bucket_name', JSON.stringify(input.bucket)],
    ['access', JSON.stringify(input.access)],
    ['role_name', input.roleName === null ? 'null' : JSON.stringify(input.roleName)]
  ])}
tags = {
${tags}
}
`
  const infra: Record<string, string> = {
    '.gitignore': GITIGNORE,
    'main.tf': MAIN,
    'outputs.tf': OUTPUTS,
    'provider.tf': 'provider "aws" {}\n',
    'terraform.tfvars': tfvars,
    'variables.tf': VARIABLES,
    'versions.tf': VERSIONS
  }
  const configExample = `# Generated by Bastion. The bucket this application uses; access is granted by the
# IAM policy in ${input.directory} (${input.access}). Copy into your runtime configuration.
${input.configVariable}=${input.bucket}
`
  return [
    ...Object.keys(infra)
      .sort()
      .map((name) => ({ path: `${input.directory}/${name}`, content: infra[name] })),
    { path: `${input.configDirectory}/${input.configVariable}.env.example`, content: configExample }
  ]
}
