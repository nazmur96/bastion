import { z } from 'zod'
import { recipeDirectorySchema, recipeTagSchema, type RecipeFile } from './object-storage-recipe'
import {
  GITIGNORE,
  PROVIDER_TF,
  ROLE_ATTACHMENT,
  ROLE_VARIABLE,
  TAGS_VARIABLE,
  VERSIONS_TF,
  hclString,
  recipeFiles,
  tfvarsWithTags
} from './recipe-hcl'

/**
 * Fork: a secret reference (Step 10.3). Creates an empty Secrets Manager secret, or connects to
 * an existing one, plus a read policy scoped to that secret. No secret value is ever written,
 * read or stored by Bastion; the application receives a reference, never a value.
 */
export const secretReferenceSchema = z
  .object({
    mode: z.enum(['create', 'existing']),
    secretName: z.string().regex(/^[A-Za-z0-9/_+=.@-]{1,256}$/),
    recoveryWindowDays: z
      .number()
      .int()
      .refine((days) => days === 0 || (days >= 7 && days <= 30)),
    directory: recipeDirectorySchema,
    roleName: z
      .string()
      .regex(/^[\w+=,.@-]{1,64}$/)
      .nullable(),
    configVariable: z.string().regex(/^[A-Z][A-Z0-9_]{0,63}$/),
    configDirectory: recipeDirectorySchema,
    tags: z.object({ owner: recipeTagSchema, project: recipeTagSchema }).strict()
  })
  .strict()
  .refine((input) => input.configDirectory !== input.directory, {
    message: 'The application config directory must differ from the infra directory.'
  })
export type SecretReference = z.infer<typeof secretReferenceSchema>

const VARIABLES = `variable "secret_name" {
  description = "Secrets Manager secret name."
  type        = string
}

variable "recovery_window_in_days" {
  description = "Days before a deleted secret is removed: 0 (immediately) or 7-30."
  type        = number
  default     = 7
}

${ROLE_VARIABLE}
${TAGS_VARIABLE}`

const CREATE = `# The value is set outside Bastion (for example aws secretsmanager put-secret-value).
resource "aws_secretsmanager_secret" "this" {
  name                    = var.secret_name
  description             = "Value managed outside Bastion; this recipe never stores it."
  recovery_window_in_days = var.recovery_window_in_days
  tags                    = var.tags
}

locals {
  secret_arn = aws_secretsmanager_secret.this.arn
}
`
const EXISTING = `# Connect, never create: plan fails if the secret does not exist.
data "aws_secretsmanager_secret" "this" {
  name = var.secret_name
}

locals {
  secret_arn = data.aws_secretsmanager_secret.this.arn
}
`
const POLICY = `
data "aws_iam_policy_document" "access" {
  statement {
    sid       = "ReadSecret"
    actions   = ["secretsmanager:GetSecretValue", "secretsmanager:DescribeSecret"]
    resources = [local.secret_arn]
  }
}

resource "aws_iam_policy" "access" {
  name        = "\${replace(var.secret_name, "/", "-")}-read"
  description = "Application read access to one secret"
  policy      = data.aws_iam_policy_document.access.json
  tags        = var.tags
}

${ROLE_ATTACHMENT}`
const OUTPUTS = `output "secret_arn" {
  value = local.secret_arn
}

output "policy_arn" {
  value = aws_iam_policy.access.arn
}
`

export function renderSecretReference(input: SecretReference): RecipeFile[] {
  const app = `# Generated by Bastion. A reference to the secret, never its value. Read the value at
# runtime with GetSecretValue; access is granted by the IAM policy in ${input.directory}.
${input.configVariable}=${input.secretName}
`
  return recipeFiles(
    input.directory,
    {
      '.gitignore': GITIGNORE,
      'main.tf': `${input.mode === 'create' ? CREATE : EXISTING}${POLICY}`,
      'outputs.tf': OUTPUTS,
      'provider.tf': PROVIDER_TF,
      'terraform.tfvars': tfvarsWithTags(
        [
          ['secret_name', JSON.stringify(input.secretName)],
          ['recovery_window_in_days', String(input.recoveryWindowDays)],
          ['role_name', hclString(input.roleName)]
        ],
        input.tags
      ),
      'variables.tf': VARIABLES,
      'versions.tf': VERSIONS_TF
    },
    [{ path: `${input.configDirectory}/${input.configVariable}.env.example`, content: app }]
  )
}
