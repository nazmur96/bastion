import { z } from 'zod'
import { recipeDirectorySchema, recipeTagSchema, type RecipeFile } from './object-storage-recipe'
import {
  GITIGNORE,
  PROVIDER_TF,
  TAGS_VARIABLE,
  VERSIONS_TF,
  recipeFiles,
  tfvarsWithTags
} from './recipe-hcl'

/**
 * Fork: Step 14.8 rotation for a Step 10 secret reference. Connect, never create: the secret
 * (and, for managed rotation, the rotation function) must already exist. Either a rotation
 * schedule run by that function, or a manual-rotation runbook. No secret value is ever
 * written, read, printed or stored by Bastion; the application keeps its reference.
 */
export const secretRotationSchema = z
  .object({
    secretName: z.string().regex(/^[A-Za-z0-9/_+=.@-]{1,256}$/),
    mode: z.enum(['function', 'manual']),
    /** An existing rotation Lambda in this account; required for `function`. */
    functionName: z
      .string()
      .regex(/^[A-Za-z0-9_-]{1,64}$/)
      .nullable(),
    everyDays: z.number().int().min(1).max(1000),
    rotateImmediately: z.boolean(),
    directory: recipeDirectorySchema,
    tags: z.object({ owner: recipeTagSchema, project: recipeTagSchema }).strict()
  })
  .strict()
  .refine((input) => (input.mode === 'function') === (input.functionName !== null), {
    message: 'Managed rotation needs a rotation function; manual rotation takes none.',
    path: ['functionName']
  })
export type SecretRotation = z.infer<typeof secretRotationSchema>

const slug = (name: string) => name.replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '')

const VARIABLES = `variable "secret_name" {
  description = "Existing Secrets Manager secret."
  type        = string
}

variable "every_days" {
  description = "Rotate this often."
  type        = number
}

${TAGS_VARIABLE}`
const FUNCTION_VARIABLES = `${VARIABLES}
variable "function_name" {
  description = "Existing rotation Lambda function in this account."
  type        = string
}

variable "rotate_immediately" {
  description = "Rotate once as soon as the schedule is applied."
  type        = bool
  default     = false
}
`
const SECRET = `# Connect, never create: plan fails if the secret does not exist.
data "aws_secretsmanager_secret" "this" {
  name = var.secret_name
}
`
const FUNCTION_MAIN = `${SECRET}
# Connect, never create: plan fails if the rotation function does not exist.
data "aws_lambda_function" "rotation" {
  function_name = var.function_name
}

# Secrets Manager may invoke the function, for this secret only.
resource "aws_lambda_permission" "rotation" {
  statement_id  = "AllowSecretsManagerRotation-\${substr(sha256(data.aws_secretsmanager_secret.this.arn), 0, 16)}"
  action        = "lambda:InvokeFunction"
  function_name = data.aws_lambda_function.rotation.function_name
  principal     = "secretsmanager.amazonaws.com"
  source_arn    = data.aws_secretsmanager_secret.this.arn
}

resource "aws_secretsmanager_secret_rotation" "this" {
  secret_id           = data.aws_secretsmanager_secret.this.id
  rotation_lambda_arn = data.aws_lambda_function.rotation.arn
  rotate_immediately  = var.rotate_immediately

  rotation_rules {
    automatically_after_days = var.every_days
  }

  depends_on = [aws_lambda_permission.rotation]
}
`
const MANUAL_MAIN = `${SECRET}
# Manual rotation: follow the runbook generated beside this recipe. Nothing here stores a value.
locals {
  rotation = "manual every \${var.every_days} days"
}
`
const OUTPUTS = `output "secret_arn" {
  value = data.aws_secretsmanager_secret.this.arn
}
`

function runbook(input: SecretRotation): RecipeFile {
  const secret = JSON.stringify(input.secretName)
  const managed = input.mode === 'function'
  return {
    path: `runbooks/rotate-${slug(input.secretName).toLowerCase().slice(0, 70)}.md`,
    content: `# Rotate ${input.secretName}

Generated by Bastion (${managed ? `managed by ${input.functionName}` : 'manual'}; every ${input.everyDays} days).
Never print, paste or log the value. The application keeps reading the secret by its name or
ARN, so its reference does not change when the value does.

## Before

- [ ] Confirm the application reads \`AWSCURRENT\` at use (or refreshes on auth failure).
- [ ] Note the current version, without the value:

      aws secretsmanager list-secret-version-ids --secret-id ${secret} \\
        --query 'Versions[?contains(VersionStages, \`AWSCURRENT\`)].VersionId' --output text

## Rotate

${
  managed
    ? `      aws secretsmanager rotate-secret --secret-id ${secret}`
    : `Generate and store a new value in one pipe; it is never shown or saved to a file.
If the credential lives in another system (a database user, an API key), change it there to the
same new value in the same step, using that system's own tooling.

      aws secretsmanager get-random-password --password-length 40 \\
          --exclude-punctuation --query RandomPassword --output text | tr -d '\\n' \\
        | aws secretsmanager put-secret-value --secret-id ${secret} \\
          --secret-string file:///dev/stdin --query VersionId --output text`
}

## Verify

- [ ] A new version holds \`AWSCURRENT\` and the previous one \`AWSPREVIOUS\`:

      aws secretsmanager list-secret-version-ids --secret-id ${secret} \\
        --query 'Versions[].[VersionId,join(\`,\`, VersionStages)]' --output text

- [ ] The application's journey check passes (Delivery page → Verify and recover).
- [ ] If it fails, move \`AWSCURRENT\` back to the previous version:

      aws secretsmanager update-secret-version-stage --secret-id ${secret} \\
        --version-stage AWSCURRENT --move-to-version-id <previous-id> \\
        --remove-from-version-id <new-id>
`
  }
}

export function renderSecretRotation(input: SecretRotation): RecipeFile[] {
  const managed = input.mode === 'function'
  const entries: [string, string][] = [
    ['secret_name', JSON.stringify(input.secretName)],
    ['every_days', String(input.everyDays)]
  ]
  if (managed) {
    entries.push(
      ['function_name', JSON.stringify(input.functionName)],
      ['rotate_immediately', String(input.rotateImmediately)]
    )
  }
  return recipeFiles(
    input.directory,
    {
      '.gitignore': GITIGNORE,
      'main.tf': managed ? FUNCTION_MAIN : MANUAL_MAIN,
      'outputs.tf': OUTPUTS,
      'provider.tf': PROVIDER_TF,
      'terraform.tfvars': tfvarsWithTags(entries, input.tags),
      'variables.tf': managed ? FUNCTION_VARIABLES : VARIABLES,
      'versions.tf': VERSIONS_TF
    },
    [runbook(input)]
  )
}
